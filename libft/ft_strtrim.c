#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	char	*ret;
	size_t	start;
	size_t	end;
	size_t	len;

	if (!s1 || !set)
		return (NULL);
	start = 0;
	end = ft_strlen(s1);
	while (start < end && ft_strchr(set, s1[start]))
		start++;
	while (end > start && ft_strchr(set, s1[end - 1]))
		end--;
	len = end - start;
	ret = malloc((len + 1) * sizeof(char));
	if (!ret)
		return (NULL);
	ft_memcpy(ret, s1 + start, len);
	ret[len] = '\0';
	return (ret);
}
